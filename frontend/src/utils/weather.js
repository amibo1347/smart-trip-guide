// 설명은 t(key) 로 다국어 표시한다.
const MAP = {
  0: ['☀️', '맑음'],
  1: ['🌤', '대체로 맑음'], 2: ['⛅', '부분 흐림'], 3: ['☁️', '흐림'],
  45: ['🌫', '안개'], 48: ['🌫', '서리 안개'],
  51: ['🌦', '약한 이슬비'], 53: ['🌦', '이슬비'], 55: ['🌧', '짙은 이슬비'],
  56: ['🌧', '어는 이슬비'], 57: ['🌧', '어는 이슬비'],
  61: ['🌦', '약한 비'], 63: ['🌧', '비'], 65: ['🌧', '강한 비'],
  66: ['🌧', '어는 비'], 67: ['🌧', '어는 비'],
  71: ['🌨', '약한 눈'], 73: ['🌨', '눈'], 75: ['❄️', '강한 눈'], 77: ['🌨', '싸락눈'],
  80: ['🌦', '약한 소나기'], 81: ['🌧', '소나기'], 82: ['⛈', '강한 소나기'],
  85: ['🌨', '소낙눈'], 86: ['❄️', '강한 소낙눈'],
  95: ['⛈', '뇌우'], 96: ['⛈', '우박 뇌우'], 99: ['⛈', '강한 우박 뇌우'],
}

/** 코드 → { emoji, key(설명 i18n 키) }. 모르는 코드는 기본값. */
export function weatherOf(code) {
  const [emoji, key] = MAP[code] ?? ['🌡', '날씨']
  return { emoji, key }
}

/** 비/눈/뇌우 계열인지 — AI 추천 등에서 '실내 위주' 판단에 쓸 수 있다. */
export function isWet(code) {
  return (code >= 51 && code <= 86) || code >= 95
}
